// 3. Database එකේ තියෙන රිපෝට් ඔක්කොම ගන්න Function එක (Doctor ට පෙන්නන්න)
exports.getAllReports = async (req, res) => {
    try {
        // අලුත්ම රිපෝට් උඩින් එන්න sort කරලා තියෙන්නේ
        const reports = await Report.find().sort({ createdAt: -1 });
        res.status(200).json(reports);
    } catch (error) {
        res.status(500).json({ message: "Error fetching reports", error: error.message });
    }
};

// 4. රෝගියාගේ නමින් රිපෝට් හොයන Function එක
exports.getPatientReports = async (req, res) => {
    try {
        const reports = await Report.find({ patientName: req.params.name }).sort({ createdAt: -1 });
        res.status(200).json(reports);
    } catch (error) {
        res.status(500).json({ message: "Error fetching patient reports", error: error.message });
    }
};
import React from 'react';

const ResultDisplay = ({ result }) => {
  //  Error State Handle
  if (result?.error) {
    return (
      <div className="rounded-3xl border border-red-200 bg-red-50 p-6">
        <p className="text-red-700 font-bold text-lg">⚠️ Analysis Failed</p>
        <p className="text-sm text-slate-600 mt-1">{result.error}</p>
      </div>
    );
  }

  if (!result) return null;

  const isDanger = Boolean(result.hasStones);
  const stoneCount = result?.stoneCount ?? 0;

  //  Phase 1 data
  const phase1Result = result?.phase1?.result || null;
  const phase1Confidence = result?.phase1?.confidence
    ? `${result.phase1.confidence.toFixed(2)}%`
    : null;

  //  Phase 2 — Average Confidence (All Stones)
  const phase2Confidence =
    result?.details?.length > 0
      ? `${(
          (result.details.reduce((sum, d) => sum + (d.confidence || 0), 0) /
            result.details.length) *
          100
        ).toFixed(2)}%`
      : 'Not available';

  //  Phase 1 Label
  const phase1Label =
    {
      stone: 'Stone Detected',
      normal: 'Normal X-Ray',
    }[phase1Result] || phase1Result;

  return (
    <div
      className={`rounded-3xl border p-6 shadow-sm ${
        isDanger
          ? 'border-red-200 bg-red-50'
          : 'border-emerald-200 bg-emerald-50'
      }`}
    >
      {/*  Header  */}
      <div className="flex flex-col gap-4 md:flex-row md:items-start md:justify-between">
        <div>
          <h2
            className={`text-2xl font-black tracking-tight ${
              isDanger ? 'text-red-700' : 'text-emerald-700'
            }`}
          >
            {isDanger ? '⚠️ Possible Stone Indicated' : '✅ No Stone Indicated'}
          </h2>
          <p className="mt-2 max-w-2xl text-sm leading-6 text-slate-600">
            This output is generated by the AI detection workflow and should
            be reviewed as part of the clinical assessment process.
          </p>
        </div>

        <span
          className={`inline-flex w-fit rounded-full px-4 py-2 text-xs font-bold ${
            isDanger
              ? 'bg-red-100 text-red-700'
              : 'bg-emerald-100 text-emerald-700'
          }`}
        >
          {isDanger ? 'Review Recommended' : 'No Immediate Flag'}
        </span>
      </div>

      {/*  Phase 1 Result Banner  */}
      {phase1Result && (
        <div
          className={`mt-4 rounded-2xl p-3 flex items-center gap-3 ${
            phase1Result === 'stone'
              ? 'bg-red-100 border border-red-200'
              : 'bg-emerald-100 border border-emerald-200'
          }`}
        >
          <span className="text-lg">
            {phase1Result === 'stone' ? '🔍' : '✔️'}
          </span>
          <div>
            <p className="text-xs font-bold uppercase tracking-widest text-slate-500">
              Phase 1 — Classification (EfficientNet-B0)
            </p>
            <p
              className={`text-sm font-bold ${
                phase1Result === 'stone'
                  ? 'text-red-700'
                  : 'text-emerald-700'
              }`}
            >
              {phase1Label} — Confidence: {phase1Confidence ?? 'N/A'}
            </p>
          </div>
        </div>
      )}

      {/*  Phase 2 Banner (Only if Stone)  */}
      {isDanger && (
        <div className="mt-3 rounded-2xl p-3 flex items-center gap-3 bg-blue-50 border border-blue-200">
          <span className="text-lg">🎯</span>
          <div>
            <p className="text-xs font-bold uppercase tracking-widest text-slate-500">
              Phase 2 — Detection (YOLOv8)
            </p>
            <p className="text-sm font-bold text-blue-700">
              {stoneCount} Stone{stoneCount !== 1 ? 's' : ''} Located —
              Avg Confidence: {phase2Confidence}
            </p>
          </div>
        </div>
      )}

      {/*  Stats Grid  */}
      <div className="mt-6 grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        {/* Detection Status */}
        <div className="rounded-2xl border border-white/60 bg-white/70 p-4">
          <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">
            Detection Status
          </p>
          <p className="mt-2 text-lg font-bold text-slate-900">
            {isDanger ? 'Positive Indication' : 'Negative Indication'}
          </p>
        </div>

        {/* Phase 1 Confidence */}
        <div className="rounded-2xl border border-white/60 bg-white/70 p-4">
          <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">
            Classification Score
          </p>
          <p className="mt-2 text-lg font-bold text-purple-600">
            {phase1Confidence || 'N/A'}
          </p>
        </div>

        {/* Phase 2 Confidence - Only if Stone */}
        {isDanger && (
          <div className="rounded-2xl border border-white/60 bg-white/70 p-4">
            <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">
              Detection Score
            </p>
            <p className="mt-2 text-lg font-bold text-blue-600">
              {phase2Confidence}
            </p>
          </div>
        )}

        {/* Stone Count */}
        <div className="rounded-2xl border border-white/60 bg-white/70 p-4">
          <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">
            Stone Count
          </p>
          <p className="mt-2 text-lg font-bold text-slate-900">
            {stoneCount}
          </p>
        </div>
      </div>

        {/*  Annotated X-Ray Image  */}
        {/*  Annotated X-Ray Image  */}
        {isDanger && result?.annotatedImageUrl && (
          <div className="mt-6 overflow-hidden rounded-2xl border border-slate-200 bg-white/70">
            <p className="px-4 pt-4 text-xs font-bold uppercase tracking-widest text-slate-500">
              🖼️ AI Annotated X-Ray
            </p>

          <img
            src={

              result.annotatedImageUrl.startsWith('blob:')

                ? result.annotatedImageUrl

                : result.annotatedImageUrl.startsWith('data:image')

                ? result.annotatedImageUrl

                : result.annotatedImageUrl.startsWith('http')

                ? result.annotatedImageUrl

              : `http://localhost:5000${
                  result.annotatedImageUrl.startsWith('/')

                    ? result.annotatedImageUrl

                    : `/${result.annotatedImageUrl}`
                }`
              }

      alt="AI Annotated X-Ray with Bounding Boxes"

      className="mt-2 w-full rounded-b-2xl object-contain"

      onError={() => {

        console.error(
          'ANNOTATED IMAGE FAILED:',
          result.annotatedImageUrl
        );
      }}
    />

  </div>

)}

      {/*  Detected Stones Detail Table  */}
      {isDanger && result?.details?.length > 0 && (
        <div className="mt-6 rounded-2xl bg-white/70 border border-slate-200 p-4">
          <p className="text-xs font-bold uppercase tracking-widest text-slate-500 mb-3">
            🪨 Detected Stone Details
          </p>

          {/* Table Header */}
          <div className="grid grid-cols-4 gap-2 mb-2 px-2">
            <p className="text-xs font-bold text-slate-400 uppercase">#</p>
            <p className="text-xs font-bold text-slate-400 uppercase">Location</p>
            <p className="text-xs font-bold text-slate-400 uppercase">Size</p>
            <p className="text-xs font-bold text-slate-400 uppercase">Confidence</p>
          </div>

          {/* Table Rows */}
          {result.details.map((stone, index) => (
            <div
              key={index}
              className="grid grid-cols-4 gap-2 mb-2 p-3 rounded-xl bg-slate-50 border border-slate-100"
            >
              <p className="text-sm font-bold text-slate-700">
                Stone {index + 1}
              </p>
              <p className="text-sm text-slate-600 font-medium">
                {stone.location || 'Unknown'}
              </p>
              <p className="text-sm text-slate-600 font-medium">
                {stone.size ? `${stone.size} mm` : 'N/A'}
              </p>
              <p className="text-sm font-bold text-blue-600">
                {stone.confidence
                  ? `${(stone.confidence * 100).toFixed(2)}%`
                  : 'N/A'}
              </p>
            </div>
          ))}
        </div>
      )}

      {/*  Recommendation Box  */}
      {isDanger && (
        <div className="mt-5 rounded-2xl border-l-4 border-orange-500 bg-orange-50 p-4">
          <p className="text-sm font-bold text-orange-800">
            ⚕️ Clinical Recommendation
          </p>
          <p className="mt-1 text-sm leading-6 text-slate-600">
            AI output suggests a possible urinary stone finding. Clinical
            review and confirmation by the responsible medical professional
            are recommended before any treatment decisions are made.
          </p>
        </div>
      )}

      {/*  Normal Result Info Box  */}
      {!isDanger && (
        <div className="mt-5 rounded-2xl border-l-4 border-emerald-500 bg-emerald-50 p-4">
          <p className="text-sm font-bold text-emerald-800">
            ✅ Normal Finding
          </p>
          <p className="mt-1 text-sm leading-6 text-slate-600">
            AI analysis indicates no urinary stone detected in this X-ray.
            Regular clinical follow-up is still advised as per standard
            medical practice.
          </p>
        </div>
      )}

      {/*  Footer Disclaimer  */}
      <div className="mt-6 rounded-2xl bg-slate-100 border border-slate-200 p-3">
        <p className="text-xs text-slate-400 text-center leading-5">
          ⚠️ This AI system is a <span className="font-bold">decision support tool only</span>.
          All results must be verified by a qualified medical professional.
          Not intended as a replacement for clinical diagnosis.
        </p>
      </div>
    </div>
  );
};

export default ResultDisplay;
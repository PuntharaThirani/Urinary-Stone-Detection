import React from 'react';

const ResultDisplay = ({ result }) => {
  if (!result) return null;

  const isDanger = Boolean(result.hasStones);
  const confidence =
    result?.details && result.details.length > 0 && result.details[0]?.confidence != null
      ? `${(result.details[0].confidence * 100).toFixed(2)}%`
      : result?.confidence || 'Not available';

  return (
    <div
      className={`rounded-3xl border p-6 shadow-sm ${
        isDanger
          ? 'border-red-200 bg-red-50'
          : 'border-emerald-200 bg-emerald-50'
      }`}
    >
      <div className="flex flex-col gap-4 md:flex-row md:items-start md:justify-between">
        <div>
          <h2
            className={`text-2xl font-black tracking-tight ${
              isDanger ? 'text-red-700' : 'text-emerald-700'
            }`}
          >
            {isDanger ? '⚠️ Possible Stone Indicated' : '✅ No Stone Indicated'}
          </h2>

          <p className="mt-2 max-w-2xl text-sm leading-6 text-slate-600">
            This output is generated by the AI detection workflow and should be reviewed
            as part of the clinical assessment process.
          </p>
        </div>

        <span
          className={`inline-flex w-fit rounded-full px-4 py-2 text-xs font-bold ${
            isDanger
              ? 'bg-red-100 text-red-700'
              : 'bg-emerald-100 text-emerald-700'
          }`}
        >
          {isDanger ? 'Review Recommended' : 'No Immediate Flag'}
        </span>
      </div>

      <div className="mt-6 grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
        <div className="rounded-2xl border border-white/60 bg-white/70 p-4">
          <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">
            Detection Status
          </p>
          <p className="mt-2 text-lg font-bold text-slate-900">
            {result.diagnosis || (isDanger ? 'Positive Indication' : 'Negative Indication')}
          </p>
        </div>

        <div className="rounded-2xl border border-white/60 bg-white/70 p-4">
          <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">
            Confidence Score
          </p>
          <p className="mt-2 text-lg font-bold text-blue-600">{confidence}</p>
        </div>

        <div className="rounded-2xl border border-white/60 bg-white/70 p-4">
          <p className="text-xs font-bold uppercase tracking-[0.14em] text-slate-500">
            AI Summary
          </p>
          <p className="mt-2 text-lg font-bold text-slate-900">
            {isDanger ? 'Further review suggested' : 'No stone highlighted'}
          </p>
        </div>
      </div>

      {isDanger && (
        <div className="mt-5 rounded-2xl border-l-4 border-orange-500 bg-orange-50 p-4">
          <p className="text-sm font-bold text-orange-800">Recommendation</p>
          <p className="mt-1 text-sm leading-6 text-slate-600">
            AI output suggests a possible urinary stone finding. Clinical review and
            confirmation by the responsible medical professional are recommended.
          </p>
        </div>
      )}
    </div>
  );
};

export default ResultDisplay;
import React, { useState } from 'react';

const HeatmapViewer = ({ originalImage, processedImage }) => {
  const [showProcessed, setShowProcessed] = useState(true);

  if (!originalImage) return null;

  const activeImage =
    showProcessed && processedImage ? processedImage : originalImage;

  return (
    <div className="rounded-3xl border border-slate-200 bg-white p-6 shadow-sm">
      <div className="mb-5 text-center">
        <h3 className="text-xl font-bold text-slate-900">Image Analysis View</h3>
        <p className="mt-2 text-sm text-slate-500">
          Switch between the original scan and the processed AI visualization.
        </p>
      </div>

      <div className="flex min-h-[320px] items-center justify-center overflow-hidden rounded-2xl border border-slate-200 bg-black">
        <img
          src={activeImage}
          alt="Scan analysis preview"
          className="max-h-[420px] max-w-full object-contain"
        />
      </div>

      <div className="mt-5 flex flex-col justify-center gap-3 sm:flex-row">
        <button
          type="button"
          onClick={() => setShowProcessed(false)}
          className={`rounded-xl px-5 py-3 text-sm font-bold transition ${
            !showProcessed
              ? 'bg-blue-600 text-white shadow-md'
              : 'bg-slate-200 text-slate-700 hover:bg-slate-300'
          }`}
        >
          Original View
        </button>

        <button
          type="button"
          onClick={() => setShowProcessed(true)}
          disabled={!processedImage}
          className={`rounded-xl px-5 py-3 text-sm font-bold transition ${
            showProcessed && processedImage
              ? 'bg-blue-600 text-white shadow-md'
              : processedImage
              ? 'bg-slate-200 text-slate-700 hover:bg-slate-300'
              : 'cursor-not-allowed bg-slate-100 text-slate-400'
          }`}
        >
          AI Detection View
        </button>
      </div>

      <div className="mt-4 rounded-2xl bg-slate-50 px-4 py-3 text-center">
        <p className="text-xs leading-6 text-slate-500">
          The AI detection view shows the processed visualization generated by the
          system, which may include highlighted regions such as bounding boxes.
        </p>
      </div>
    </div>
  );
};

export default HeatmapViewer;